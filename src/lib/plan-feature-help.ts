export function getPlanFeatureHelp(
  id: PlanFeatureId,
  plan?: SubscriptionPlan,
  label?: string,
): FeatureHelpContent {
  const source = explanations[id];
  const title = `${label ?? source.title}${plan ? ` — ${plan.id}` : ""}`;
  if (id === "seo")
    return {
      title,
      sections: (plan ? [plan] : plans).map((item) => ({
        title: plan ? undefined : `${item.id} — ${item.seo}`,
        summary: seoSummaries[item.id],
      })),
      note:
        plan?.proposed || !plan
          ? "Обхватът за BUSINESS и PREMIUM остава предложен до потвърждение."
          : undefined,
    };
  const limits: Partial<Record<PlanFeatureId, string>> = plan
    ? {
        pages: `До ${plan.pages} основни страници. `,
        monthlyChanges: `До ${monthlyTimeLabel(plan)} месечно. `,
        email: `${plan.emailGb} GB общо пространство. `,
      }
    : {};
  const limit = limits[id];
  return {
    title,
    sections: [
      {
        summary: limit
          ? [{ strong: limit }, ...source.summary]
          : source.summary,
      },
    ],
    note: plan?.proposed
      ? "Това е предложен обхват. Окончателните параметри се потвърждават в индивидуалната оферта."
      : undefined,
  };
}
